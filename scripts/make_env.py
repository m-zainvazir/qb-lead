"""Create local env files from the running local Supabase stack.

    python scripts/make_env.py           # creates .env and apps/web/.env.local if missing
    python scripts/make_env.py --merge   # adds keys that are missing, never changes existing ones

LOCAL ONLY. It refuses to run when the Supabase status does not point at 127.0.0.1.
Generated passwords are random per machine; nothing here is committed.
"""

from __future__ import annotations

import argparse
import json
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROOT_ENV = ROOT / ".env"
WEB_ENV = ROOT / "apps" / "web" / ".env.local"


def supabase_status() -> dict[str, str]:
    npx = shutil.which("npx") or "npx"
    out = subprocess.run(  # noqa: S603 - fixed command, no user input
        [npx, "supabase", "status", "-o", "json"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    status: dict[str, str] = json.loads(out[out.index("{") :])
    if "127.0.0.1" not in status.get("API_URL", ""):
        sys.exit("Supabase status does not point at a local stack; refusing.")
    return status


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.lstrip().startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip()
    return values


def write_env(path: Path, wanted: dict[str, str], merge: bool) -> None:
    existing = read_env(path)
    if existing and not merge:
        missing = [k for k in wanted if k not in existing]
        print(f"{path.relative_to(ROOT)} exists; missing keys: {missing or 'none'}")
        if missing:
            print("  re-run with --merge to append them (existing values are kept)")
        return
    to_add = {k: v for k, v in wanted.items() if k not in existing}
    if not to_add:
        print(f"{path.relative_to(ROOT)}: nothing to add")
        return
    with path.open("a", encoding="utf-8", newline="\n") as fh:
        if not existing:
            fh.write("# Generated by scripts/make_env.py for the LOCAL stack only.\n")
        for key, value in to_add.items():
            fh.write(f"{key}={value}\n")
    print(f"{path.relative_to(ROOT)}: added {sorted(to_add)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--merge", action="store_true")
    args = parser.parse_args()

    st = supabase_status()
    existing = read_env(ROOT_ENV)
    app_pw = existing.get("APP_DB_PASSWORD") or secrets.token_urlsafe(24)
    sys_pw = existing.get("SYSTEM_DB_PASSWORD") or secrets.token_urlsafe(24)
    redis_pw = existing.get("REDIS_PASSWORD") or secrets.token_urlsafe(24)
    db_host = "127.0.0.1:54322/postgres"

    root_env = {
        "APP_ENV": "local",
        "LOG_LEVEL": "INFO",
        "GIT_COMMIT": "dev",
        "SUPABASE_URL": st["API_URL"],
        "SUPABASE_ANON_KEY": st["ANON_KEY"],
        "SUPABASE_SERVICE_ROLE_KEY": st["SERVICE_ROLE_KEY"],
        "SUPABASE_JWT_SECRET": st["JWT_SECRET"],
        "APP_DB_PASSWORD": app_pw,
        "SYSTEM_DB_PASSWORD": sys_pw,
        "DATABASE_URL_API": f"postgresql://app_api:{app_pw}@{db_host}",
        "DATABASE_URL_SYSTEM": f"postgresql://app_system:{sys_pw}@{db_host}",
        "DATABASE_URL_ADMIN": st["DB_URL"],
        "REDIS_PASSWORD": redis_pw,
        "REDIS_URL": f"redis://:{redis_pw}@127.0.0.1:6379/0",
        "WEB_BASE_URL": "http://localhost:3000",
        "SMTP_HOST": "127.0.0.1",
        "SMTP_PORT": "54325",
        "SMTP_FROM": "no-reply@leadgen.local",
        "MAILGUN_SIGNING_KEY": existing.get("MAILGUN_SIGNING_KEY") or secrets.token_hex(24),
        "INBOUND_EMAIL_DOMAIN": "in.leadgen.local",
    }
    web_env = {
        # Server-side only: none of these are NEXT_PUBLIC_, so none reach the browser bundle.
        "SUPABASE_URL": st["API_URL"],
        "SUPABASE_ANON_KEY": st["ANON_KEY"],
        "API_URL": "http://localhost:8000",
        "WEB_BASE_URL": "http://localhost:3000",
    }
    write_env(ROOT_ENV, root_env, args.merge)
    write_env(WEB_ENV, web_env, args.merge)


if __name__ == "__main__":
    main()
